fn python_file(path: &str) -> SourceFile {
    SourceFile {
        path: path.to_owned(),
        language: "python".to_owned(),
        symbols: Vec::new(),
    }
}

#[test]
fn exact_real_mypy_strictly_checks_bound_source_and_records_identity() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("app.py"),
        "def identity(value: int) -> int:\n    return value\n",
    )
    .unwrap();

    let verification = typecheck_request_sources(directory.path(), &[python_file("app.py")], &[])
        .expect("the pinned checker must be available for the issuance test")
        .expect("the request contains Python");
    assert!(verification.passed(), "{verification:#?}");
    assert_eq!(verification.identity.checker, "mypy");
    assert_eq!(verification.identity.checker_version, MYPY_VERSION);
    assert_eq!(verification.identity.profile, "strict-issuance");
    assert_eq!(verification.identity.package_sha256.len(), 64);
    assert_eq!(verification.identity.runtime_executable_sha256.len(), 64);
    assert_eq!(verification.identity.runtime_bundle_sha256.len(), 64);
    assert_eq!(verification.identity.configuration_sha256.len(), 64);
    assert_eq!(
        verification
            .identity
            .contract_support_sha256
            .as_deref()
            .map(str::len),
        Some(64)
    );

    let repeated = typecheck_request_sources(directory.path(), &[python_file("app.py")], &[])
        .expect("the pinned checker must remain available")
        .expect("the request contains Python");
    assert_eq!(
        repeated.identity, verification.identity,
        "toolchain identity must not depend on generated bytecode caches or temporary paths"
    );
}

#[test]
fn concurrent_typechecks_keep_mypy_cache_out_of_the_shared_source_root() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("app.py"),
        "def identity(value: int) -> int:\n    return value\n",
    )
    .unwrap();

    let (first, second) = std::thread::scope(|scope| {
        let first = scope
            .spawn(|| typecheck_request_sources(directory.path(), &[python_file("app.py")], &[]));
        let second = scope
            .spawn(|| typecheck_request_sources(directory.path(), &[python_file("app.py")], &[]));
        (first.join().unwrap(), second.join().unwrap())
    });
    let first = first.unwrap().unwrap();
    let second = second.unwrap().unwrap();
    assert!(first.passed(), "{first:#?}");
    assert!(second.passed(), "{second:#?}");
    assert_eq!(first.identity, second.identity);
    assert!(
        !directory.path().join(".mypy_cache").exists(),
        "mypy cache escaped its invocation-owned overlay workspace"
    );
}

#[test]
fn strict_type_errors_are_located_and_block_proof_issuance() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("app.py"),
        "def wrong(value: int) -> str:\n    return value\n",
    )
    .unwrap();
    let request = ProofRequest {
        schema: PROTOCOL_SCHEMA.to_owned(),
        source_root: directory.path().display().to_string(),
        source_fingerprint: "0".repeat(64),
        proof_obligation: "no-undeclared-exceptional-exit".to_owned(),
        files: vec![SourceFile {
            path: "app.py".to_owned(),
            language: "python".to_owned(),
            symbols: vec!["wrong".to_owned()],
        }],
        external_contract_overlays: Vec::new(),
        python_callable_bindings: Vec::new(),
        cross_language_bindings: Vec::new(),
    };

    let response = maledictus::verify(&request);
    assert!(
        matches!(response.status, ProofStatus::Refused),
        "{response:#?}"
    );
    assert!(response.python_typechecker.is_some(), "{response:#?}");
    assert_eq!(response.diagnostics.len(), 1, "{response:#?}");
    assert_eq!(
        response.diagnostics[0].code,
        "frontend.python.typecheck.return-value"
    );
    assert_eq!(response.diagnostics[0].path.as_deref(), Some("app.py"));
    assert_eq!(response.diagnostics[0].line, Some(2));
    assert_eq!(response.diagnostics[0].column, Some(12));
    assert!(response.files.is_empty(), "proof lowering must not begin");
}

