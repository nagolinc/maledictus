#[test]
fn non_issuing_analysis_is_explicit_and_cannot_bypass_verify() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("app.py"),
        "def wrong(value: int) -> str:\n    return value\n",
    )
    .unwrap();
    let request = ProofRequest {
        schema: PROTOCOL_SCHEMA.to_owned(),
        source_root: directory.path().display().to_string(),
        source_fingerprint: "0".repeat(64),
        proof_obligation: "no-undeclared-exceptional-exit".to_owned(),
        files: vec![SourceFile {
            path: "app.py".to_owned(),
            language: "python".to_owned(),
            symbols: vec!["wrong".to_owned()],
        }],
        external_contract_overlays: Vec::new(),
        python_callable_bindings: Vec::new(),
        cross_language_bindings: Vec::new(),
    };

    let issuance = maledictus::verify(&request);
    assert!(matches!(issuance.status, ProofStatus::Refused));
    assert!(issuance.python_typechecker.is_some());
    assert!(issuance.files.is_empty(), "proof lowering must not begin");

    let analysis = analyze_python_frontend(&request);
    assert!(
        matches!(
            analysis.disposition,
            FrontendDisposition::Supported
                | FrontendDisposition::Refuted
                | FrontendDisposition::Unsupported
        ),
        "{analysis:#?}"
    );
    assert!(!analysis.files.is_empty(), "{analysis:#?}");
    assert!(
        analysis
            .diagnostics
            .iter()
            .all(|item| !item.code.starts_with("frontend.python.typecheck.")),
        "{analysis:#?}"
    );
}

#[test]
fn protocol_and_verify_cli_reject_an_analysis_mode_switch() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("app.py"),
        "def identity(value: int) -> int:\n    return value\n",
    )
    .unwrap();
    let request = ProofRequest {
        schema: PROTOCOL_SCHEMA.to_owned(),
        source_root: directory.path().display().to_string(),
        source_fingerprint: "0".repeat(64),
        proof_obligation: "no-undeclared-exceptional-exit".to_owned(),
        files: vec![python_file("app.py")],
        external_contract_overlays: Vec::new(),
        python_callable_bindings: Vec::new(),
        cross_language_bindings: Vec::new(),
    };
    let mut encoded = serde_json::to_value(&request).unwrap();
    encoded["analysis"] = serde_json::Value::Bool(true);
    assert!(serde_json::from_value::<ProofRequest>(encoded.clone()).is_err());

    let request_path = directory.path().join("request.json");
    fs::write(&request_path, serde_json::to_vec_pretty(&encoded).unwrap()).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_maledictus"))
        .args(["verify", "--request"])
        .arg(request_path)
        .output()
        .unwrap();
    assert!(!output.status.success());
    assert!(output.stdout.is_empty());
}
