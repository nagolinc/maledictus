#[test]
fn unrequested_local_imports_cannot_influence_a_clean_typecheck() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("provider.py"),
        "def value() -> int:\n    return 1\n",
    )
    .unwrap();
    fs::write(
        directory.path().join("app.py"),
        "from provider import value\n\ndef read() -> int:\n    return value()\n",
    )
    .unwrap();

    let refused = typecheck_request_sources(directory.path(), &[python_file("app.py")], &[])
        .unwrap()
        .unwrap();
    assert!(!refused.passed(), "{refused:#?}");
    assert!(refused.diagnostics.iter().any(|diagnostic| {
        diagnostic.code == "frontend.python.typecheck.misc" && diagnostic.line == Some(1)
    }));

    let closed = typecheck_request_sources(
        directory.path(),
        &[python_file("app.py"), python_file("provider.py")],
        &[],
    )
    .unwrap()
    .unwrap();
    assert!(closed.passed(), "{closed:#?}");
}

#[test]
fn declared_external_overlay_is_a_typed_explicit_input_not_an_ignored_import() {
    let directory = tempfile::tempdir().unwrap();
    fs::write(
        directory.path().join("app.py"),
        "from provider import positive\nfrom nagini_contracts.contracts import *\n\ndef run() -> int:\n    Ensures(Result() == 2)\n    value = positive(1)\n    return value\n",
    )
    .unwrap();
    fs::write(
        directory.path().join("provider_contract.py"),
        "from nagini_contracts.contracts import *\n\n@ContractOnly\ndef positive(value: int) -> int:\n    Requires(value > 0)\n    Ensures(int, lambda returned: returned == value + 1)\n    ...\n",
    )
    .unwrap();
    let overlay = ExternalOverlay {
        adapter_path: "app.py".to_owned(),
        module: "provider".to_owned(),
        stub_path: "provider_contract.py".to_owned(),
        exception_policy: ExternalExceptionPolicy::AssumeNoException,
    };

    let verification =
        typecheck_request_sources(directory.path(), &[python_file("app.py")], &[overlay])
            .unwrap()
            .unwrap();
    assert!(verification.passed(), "{verification:#?}");
}

